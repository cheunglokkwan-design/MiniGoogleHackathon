// Builds ./extension (load it via chrome://extensions → Load unpacked).
// The extension reuses the exact same app as the website.
import { cpSync, mkdirSync, rmSync, readFileSync, writeFileSync } from 'node:fs';

const OUT = 'extension';
rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

for (const f of ['style.css', 'app.js', 'scene3d.js', 'examples.js']) cpSync(f, `${OUT}/${f}`);
for (const d of ['lib', 'vendor', 'extension-src/icons']) cpSync(d, `${OUT}/${d.replace('extension-src/', '')}`, { recursive: true });
cpSync('extension-src/manifest.json', `${OUT}/manifest.json`);
cpSync('extension-src/background.js', `${OUT}/background.js`);
writeFileSync(`${OUT}/app.html`, readFileSync('index.html', 'utf8'));
writeFileSync(`${OUT}/README.txt`, 'Generated by `npm run build:ext` — edit the files in the repo root / extension-src instead.\n');
console.log('Built ./extension — load it in chrome://extensions with "Load unpacked".');
